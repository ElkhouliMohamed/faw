/** Icône par nom (décorative). Nom vide ou inconnu : `fallback`, ou rien. */
export function HomeIcon({ name, className = "size-6", strokeWidth = 1.6, fallback }: { name: string; className?: string; strokeWidth?: number; fallback?: string }) {
  const Icon = ICONS[name] ?? (fallback ? ICONS[fallback] : undefined);
  return Icon ? <Icon className={className} strokeWidth={strokeWidth} aria-hidden /> : null;
}
